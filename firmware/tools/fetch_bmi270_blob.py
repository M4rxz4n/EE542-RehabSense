#!/usr/bin/env python3
"""
Generate main/imu/bmi270_config_blob.c from Bosch's BMI270 Sensor API.

The BMI270 needs an ~8 kB configuration image uploaded at every power-on
before it produces any data. Bosch ships that image as a C array inside
bmi270.c in their public API repo. It is their code under their licence, so
this project pulls it at setup time rather than vendoring it.

Usage:
    python tools/fetch_bmi270_blob.py                # download from GitHub
    python tools/fetch_bmi270_blob.py path/to/bmi270.c   # use a local copy

Offline? Grab the file yourself from
https://github.com/boschsensortec/BMI270-Sensor-API/blob/master/bmi270.c
and pass its path as the argument.
"""

import re
import sys
import pathlib
import urllib.request

SOURCE_URL = ("https://raw.githubusercontent.com/boschsensortec/"
              "BMI270-Sensor-API/master/bmi270.c")

OUT = pathlib.Path(__file__).resolve().parent.parent / "main" / "imu" / "bmi270_config_blob.c"

ARRAY_RE = re.compile(
    r"bmi270_config_file\s*\[\s*\]\s*=\s*\{(.*?)\};", re.DOTALL)


def load_source(argv):
    if len(argv) > 1:
        path = pathlib.Path(argv[1])
        print(f"reading {path}")
        return path.read_text(encoding="utf-8", errors="replace")
    print(f"downloading {SOURCE_URL}")
    with urllib.request.urlopen(SOURCE_URL, timeout=60) as resp:
        return resp.read().decode("utf-8", errors="replace")


def extract_bytes(text):
    m = ARRAY_RE.search(text)
    if not m:
        raise SystemExit(
            "could not find bmi270_config_file[] in the source.\n"
            "Bosch may have restructured the file — open it and look for the\n"
            "large uint8_t array, then adjust ARRAY_RE in this script.")
    body = m.group(1)
    vals = re.findall(r"0[xX][0-9a-fA-F]{1,2}", body)
    if not vals:
        raise SystemExit("found the array but no hex byte values in it.")
    return [int(v, 16) for v in vals]


def write_c(data):
    lines = [
        "/* GENERATED by tools/fetch_bmi270_blob.py — do not edit by hand.",
        " *",
        " * BMI270 configuration image, from Bosch's BMI270-Sensor-API.",
        " * Copyright Bosch Sensortec; see that project for licence terms.",
        " */",
        "",
        '#include "bmi270_config_blob.h"',
        "",
        f"static const uint8_t s_blob[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i:i + 12])
        lines.append(f"    {chunk},")
    lines += [
        "};",
        "",
        "const uint8_t *bmi270_config_file = s_blob;",
        f"const size_t   bmi270_config_file_len = {len(data)};",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")


def main():
    data = extract_bytes(load_source(sys.argv))

    # Sanity check: the real image is a little over 8 kB. Anything far off
    # means the regex matched the wrong array.
    if not (6000 < len(data) < 10000):
        raise SystemExit(
            f"extracted {len(data)} bytes, expected roughly 8 kB. "
            "The regex probably matched the wrong array — check the source.")

    if len(data) % 2:
        raise SystemExit(
            f"blob length {len(data)} is odd; INIT_ADDR indexes 16-bit words "
            "so the upload would misalign.")

    write_c(data)
    print(f"wrote {OUT} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
